# CREATE PRODUCT
# --------------------------------------------------

@inventory_bp.route("/new", methods=["GET", "POST"])
@login_required
def create_product():
    if request.method == "GET":
        return render_template(
            "product_form.html",
            product=None,
        )

    values, errors = parse_product_form()

    if values["sku"] and Product.query.filter_by(
        sku=values["sku"]
    ).first():
        errors.append("That SKU is already in use.")

    if errors:
        for error in errors:
            flash(error, "error")

        return render_template(
            "product_form.html",
            product=None,
        ), 400

    try:
        image_filename = save_product_image(
            request.files.get("image")
        )
    except ValueError as error:
        flash(str(error), "error")
        return render_template(
            "product_form.html",
            product=None,
        ), 400

    product = Product(
        name=values["name"],
        sku=values["sku"],
        description=values["description"],
        quantity=values["quantity"],
        unit_price=values["unit_price"],
        image_filename=image_filename,
        owner_id=current_user.id,
    )

    db.session.add(product)

    try:
        db.session.commit()

    except IntegrityError:
        db.session.rollback()
        delete_product_image(image_filename)

        flash(
            "The product could not be saved. "
            "Check that its SKU is unique.",
            "error",
        )

        return render_template(
            "product_form.html",
            product=None,
        ), 400

    flash("Product created successfully.", "success")

    return redirect(
        url_for("inventory.list_products")
    )


