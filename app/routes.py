# EDIT PRODUCT
# --------------------------------------------------

@inventory_bp.route(
    "/<int:product_id>/edit",
    methods=["GET", "POST"],
)
@login_required
def edit_product(product_id):
    # Prevent users from editing another user's product.
    product = Product.query.filter_by(
        id=product_id,
        owner_id=current_user.id,
    ).first_or_404()

    if request.method == "GET":
        return render_template(
            "product_form.html",
            product=product,
        )

    values, errors = parse_product_form()

    duplicate = Product.query.filter(
        Product.sku == values["sku"],
        Product.id != product.id,
    ).first()

    if duplicate:
        errors.append("That SKU is already in use.")

    if errors:
        for error in errors:
            flash(error, "error")

        return render_template(
            "product_form.html",
            product=product,
        ), 400

    old_image_filename = product.image_filename

    try:
        new_image_filename = save_product_image(
            request.files.get("image")
        )
    except ValueError as error:
        flash(str(error), "error")

        return render_template(
            "product_form.html",
            product=product,
        ), 400

    product.name = values["name"]
    product.sku = values["sku"]
    product.description = values["description"]
    product.quantity = values["quantity"]
    product.unit_price = values["unit_price"]

    if new_image_filename:
        product.image_filename = new_image_filename

    try:
        db.session.commit()

    except IntegrityError:
        db.session.rollback()
        delete_product_image(new_image_filename)

        flash(
            "The product could not be updated. "
            "Check that its SKU is unique.",
            "error",
        )

        return render_template(
            "product_form.html",
            product=product,
        ), 400

    # Delete the previous image only after the update succeeds.
    if new_image_filename and old_image_filename:
        delete_product_image(old_image_filename)

    flash("Product updated successfully.", "success")

    return redirect(
        url_for("inventory.list_products")
    )


# --------------------------------------------------
# DELETE PRODUCT
# --------------------------------------------------

@inventory_bp.route(
    "/<int:product_id>/delete",
    methods=["POST"],
)
@login_required
def delete_product(product_id):
    # Prevent users from deleting another user's product.
    product = Product.query.filter_by(
        id=product_id,
        owner_id=current_user.id,
    ).first_or_404()

    image_filename = product.image_filename

    db.session.delete(product)

    try:
        db.session.commit()

    except IntegrityError:
        db.session.rollback()

        flash(
            "This product cannot be deleted because it is "
            "referenced by an existing order.",
            "error",
        )

        return redirect(
            url_for("inventory.list_products")
        )

    delete_product_image(image_filename)

    flash("Product deleted successfully.", "success")

    return redirect(
        url_for("inventory.list_products")
    )


# --------------------------------------------------
# DISPLAY PRODUCT IMAGE
# --------------------------------------------------

@inventory_bp.get("/images/<filename>")
@login_required
def product_image(filename):
    # Only accept the random filename format generated above.
    valid_filename = any(
        filename.endswith(extension)
        and len(filename) == 32 + len(extension)
        and all(
            character in "0123456789abcdef"
            for character in filename[:-len(extension)]
        )
        for extension in ALLOWED_IMAGE_FORMATS.values()
    )

    if not valid_filename:
        abort(404)

    # Only serve an image belonging to the logged-in user.
    product = Product.query.filter_by(
        image_filename=filename,
        owner_id=current_user.id,
    ).first()

    if product is None:
        abort(404)

    extension = os.path.splitext(filename)[1].lower()

    mimetypes = {
        ".jpg": "image/jpeg",
        ".png": "image/png",
        ".webp": "image/webp",
    }

    return send_from_directory(
        current_app.config["UPLOAD_FOLDER"],
        filename,
        mimetype=mimetypes[extension],
        as_attachment=False,
        max_age=3600,
    )
