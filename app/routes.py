
import os
import uuid
from decimal import Decimal, InvalidOperation
from io import BytesIO

from flask import (
    Blueprint,
    abort,
    current_app,
    flash,
    redirect,
    render_template,
    request,
    send_from_directory,
    url_for,
)
from flask_login import current_user, login_required
from PIL import Image, UnidentifiedImageError
from sqlalchemy import or_
from sqlalchemy.exc import IntegrityError

from app import db
from app.models import Product


inventory_bp = Blueprint(
    "inventory",
    __name__,
    url_prefix="/inventory",
)

ALLOWED_IMAGE_FORMATS = {
    "JPEG": ".jpg",
    "PNG": ".png",
    "WEBP": ".webp",
}

MAX_IMAGE_BYTES = 5 * 1024 * 1024
MAX_IMAGE_PIXELS = 20_000_000


# --------------------------------------------------
# IMAGE UPLOAD
# --------------------------------------------------

def save_product_image(file):
    """Validate and save an image with a random filename."""
    if file is None or not file.filename:
        return None

    # Read at most one byte beyond the permitted limit.
    image_data = file.read(MAX_IMAGE_BYTES + 1)

    if not image_data:
        raise ValueError("The selected image is empty.")

    if len(image_data) > MAX_IMAGE_BYTES:
        raise ValueError("Images must be 5 MB or smaller.")

    try:
        with Image.open(BytesIO(image_data)) as image:
            image_format = image.format

            if image_format not in ALLOWED_IMAGE_FORMATS:
                raise ValueError(
                    "Only JPEG, PNG, and WebP images are allowed."
                )

            if getattr(image, "is_animated", False):
                raise ValueError(
                    "Animated images are not allowed."
                )

            if image.width * image.height > MAX_IMAGE_PIXELS:
                raise ValueError("Image dimensions are too large.")

            image.verify()

        # Reopen and fully decode the image to detect corrupt data.
        with Image.open(BytesIO(image_data)) as image:
            if image.width * image.height > MAX_IMAGE_PIXELS:
                raise ValueError("Image dimensions are too large.")

            image.load()

    except (
        UnidentifiedImageError,
        OSError,
        Image.DecompressionBombError,
    ):
        raise ValueError(
            "The uploaded file is not a valid image."
        ) from None

    filename = (
        f"{uuid.uuid4().hex}"
        f"{ALLOWED_IMAGE_FORMATS[image_format]}"
    )

    upload_folder = current_app.config["UPLOAD_FOLDER"]
    os.makedirs(upload_folder, exist_ok=True)

    file_path = os.path.join(upload_folder, filename)

    try:
        # Exclusive creation prevents accidental overwrites.
        with open(file_path, "xb") as destination:
            destination.write(image_data)
    except OSError:
        raise ValueError("The image could not be saved.") from None

    return filename


def delete_product_image(filename):
    """Safely delete an image generated by this module."""
    if not filename:
        return

    # Accept only our 32-character hexadecimal filenames.
    valid_filename = any(
        filename.endswith(extension)
        and len(filename) == 32 + len(extension)
        and all(
            character in "0123456789abcdef"
            for character in filename[:-len(extension)]
        )
        for extension in ALLOWED_IMAGE_FORMATS.values()
    )

    if not valid_filename:
        current_app.logger.warning(
            "Skipped deletion of an unexpected image filename."
        )
        return

    upload_folder = os.path.realpath(
        current_app.config["UPLOAD_FOLDER"]
    )
    file_path = os.path.realpath(
        os.path.join(upload_folder, filename)
    )

    # Ensure the file is directly inside the upload directory.
    if os.path.dirname(file_path) != upload_folder:
        current_app.logger.warning(
            "Skipped image deletion outside upload folder."
        )
        return

    try:
        os.remove(file_path)
    except FileNotFoundError:
        pass
    except OSError:
        current_app.logger.exception(
            "Could not delete a product image."
        )


# --------------------------------------------------
# PRODUCT FORM VALIDATION
# --------------------------------------------------

def parse_product_form():
    """Validate submitted product fields."""
    name = request.form.get("name", "").strip()
    sku = request.form.get("sku", "").strip().upper()
    description = request.form.get("description", "").strip()
    quantity_text = request.form.get("quantity", "").strip()
    price_text = request.form.get("unit_price", "").strip()

    errors = []

    if not name or len(name) > 120:
        errors.append(
            "Product name is required and must be at most "
            "120 characters."
        )

    if not sku or len(sku) > 60:
        errors.append(
            "SKU is required and must be at most 60 characters."
        )

    if len(description) > 5000:
        errors.append(
            "Description must be 5,000 characters or fewer."
        )

    quantity = None

    try:
        if not quantity_text or len(quantity_text) > 9:
            raise ValueError

        quantity = int(quantity_text)

        if quantity < 0 or quantity > 1_000_000:
            raise ValueError

    except ValueError:
        errors.append(
            "Quantity must be a whole number from 0 to 1,000,000."
        )

    price = None

    try:
        if not price_text or len(price_text) > 20:
            raise ValueError

        price = Decimal(price_text)

        if (
            not price.is_finite()
            or price < 0
            or price > Decimal("99999999.99")
            or price.as_tuple().exponent < -2
        ):
            raise ValueError

    except (ValueError, InvalidOperation):
        errors.append(
            "Price must be a valid non-negative amount "
            "with at most two decimal places."
        )

    values = {
        "name": name,
        "sku": sku,
        "description": description,
        "quantity": quantity,
        "unit_price": price,
    }

    return values, errors


# --------------------------------------------------
# LIST AND SEARCH PRODUCTS
# --------------------------------------------------

@inventory_bp.get("/")
@login_required
def list_products():
    search = request.args.get("q", "").strip()

    if len(search) > 100:
        flash(
            "Search text must be 100 characters or fewer.",
            "error",
        )
        search = ""

    # Staff members can see only their own products.
    query = Product.query.filter_by(
        owner_id=current_user.id,
    )

    if search:
        pattern = f"%{search}%"

        query = query.filter(
            or_(
                Product.name.ilike(pattern),
                Product.sku.ilike(pattern),
            )
        )

    products = query.order_by(Product.name.asc()).all()

    return render_template(
        "inventory.html",
        products=products,
        search=search,
    )


